/* FBKK_DESKTOP_SECTION_WHEEL_AND_ARROW_NAV */
(function () {
  const ids = ["top", "events", "news", "docs", "sponsors", "contacts"];
  const desktopQuery = window.matchMedia(
    "(min-width:1101px) and (pointer:fine)",
  );
  const reducedMotionQuery = window.matchMedia(
    "(prefers-reduced-motion: reduce)",
  );
  const desktop = () => desktopQuery.matches;
  const reduce = () => reducedMotionQuery.matches;
  let lockedUntil = 0;
  const sections = () =>
    ids.map((id) => document.getElementById(id)).filter(Boolean);
  const activeIndex = (nodes) => {
    const y = window.scrollY;
    let best = 0,
      dist = Infinity;
    nodes.forEach((node, i) => {
      const d = Math.abs(node.getBoundingClientRect().top);
      if (d < dist) {
        dist = d;
        best = i;
      }
    });
    return best;
  };
  function move(direction) {
    const now = performance.now();
    if (now < lockedUntil) return;
    const nodes = sections(),
      i = activeIndex(nodes),
      current = nodes[i];
    if (!current) return;
    const rect = current.getBoundingClientRect();
    const tall = rect.height > innerHeight + 30;
    if (tall) {
      if (direction > 0 && rect.bottom > innerHeight + 45) {
        window.scrollBy({
          top: Math.min(innerHeight * 0.82, rect.bottom - innerHeight),
          behavior: reduce() ? "instant" : "smooth",
        });
        lockedUntil = now + 420;
        return;
      }
      if (direction < 0 && rect.top < -45) {
        window.scrollBy({
          top: -Math.min(innerHeight * 0.82, -rect.top),
          behavior: reduce() ? "instant" : "smooth",
        });
        lockedUntil = now + 420;
        return;
      }
    }
    const next = nodes[Math.max(0, Math.min(nodes.length - 1, i + direction))];
    if (next === current) return;
    lockedUntil = now + (reduce() ? 180 : 680);
    next.scrollIntoView({
      behavior: reduce() ? "instant" : "smooth",
      block: "start",
    });
  }
  function editable(el) {
    return !!el?.closest(
      'input,textarea,select,[contenteditable="true"],[role="dialog"],[role="listbox"]',
    );
  }
  function insideScrollable(el, dy) {
    for (
      let node = el;
      node && node !== document.body;
      node = node.parentElement
    ) {
      if (!(node instanceof HTMLElement)) continue;
      const cs = getComputedStyle(node);
      if (
        !/(auto|scroll)/.test(cs.overflowY) ||
        node.scrollHeight <= node.clientHeight + 3
      )
        continue;
      if (dy > 0 && node.scrollTop + node.clientHeight < node.scrollHeight - 3)
        return true;
      if (dy < 0 && node.scrollTop > 3) return true;
    }
    return false;
  }
  window.addEventListener(
    "wheel",
    (e) => {
      if (
        !desktop() ||
        e.ctrlKey ||
        e.metaKey ||
        e.shiftKey ||
        Math.abs(e.deltaY) < 4 ||
        editable(e.target)
      )
        return;
      if (insideScrollable(e.target, e.deltaY)) return;
      e.preventDefault();
      move(Math.sign(e.deltaY));
    },
    { passive: false },
  );
  window.addEventListener("keydown", (e) => {
    if (!desktop() || e.altKey || e.ctrlKey || e.metaKey || editable(e.target))
      return;
    if (
      e.key !== "ArrowDown" &&
      e.key !== "ArrowUp" &&
      e.key !== "PageDown" &&
      e.key !== "PageUp"
    )
      return;
    e.preventDefault();
    move(e.key === "ArrowDown" || e.key === "PageDown" ? 1 : -1);
  });
})();

