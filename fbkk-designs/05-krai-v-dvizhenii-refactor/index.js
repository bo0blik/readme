/* FBKK_RESTORE_MAP_FACET_TEXTURES */
(function () {
  const map = document.getElementById("mapLayers");
  if (!map) return;
  const palettes = {
    lavender: "#6A35E6",
    ocean: "#008FBE",
    coral: "#E64A65",
    emerald: "#008D73",
    gold: "#BB8525",
    neon: "#8E40EF",
    arctic: "#397AE5",
    forest: "#4B973C",
    sakura: "#DA4E9D",
    graphite: "#596A87",
    cosmos: "#7943D9",
    dawn: "#E77775",
    aurora: "#12A7A7",
    citrus: "#F18A18",
    indigo: "#5357D8",
    mint: "#28B5A7",
  };
  const hexRgb = (hex) => {
    const v = hex.replace("#", "");
    return [0, 2, 4].map((i) => parseInt(v.slice(i, i + 2), 16));
  };
  const toHsl = (rgb) => {
    const [r, g, b] = rgb.map((x) => x / 255);
    const max = Math.max(r, g, b),
      min = Math.min(r, g, b),
      d = max - min;
    let h = 0,
      s = 0,
      l = (max + min) / 2;
    if (d) {
      s = d / (1 - Math.abs(2 * l - 1));
      switch (max) {
        case r:
          h = ((g - b) / d) % 6;
          break;
        case g:
          h = (b - r) / d + 2;
          break;
        default:
          h = (r - g) / d + 4;
      }
      h = (h * 60 + 360) % 360;
    }
    return [h, s, l];
  };
  const originalFacetLightness = new WeakMap();

  function repaint() {
    const theme = document.documentElement.dataset.fbkkTheme || "lavender";
    const facets = map.querySelectorAll("#shards .shard");
    if (!facets.length) return;
    const [hue, saturation, baseLightness] = toHsl(
      hexRgb(palettes[theme] || palettes.lavender),
    );
    const facetSaturation = Math.max(0.42, Math.min(0.94, saturation * 0.92));
    const facetHue = hue.toFixed(1);
    facets.forEach((poly) => {
      const original = poly.getAttribute("fill");
      if (!original || !/^#[0-9a-f]{6}$/i.test(original)) return;
      if (theme === "lavender") {
        poly.style.removeProperty("fill");
        return;
      }
      let oldL = originalFacetLightness.get(poly);
      if (oldL === undefined) {
        oldL = toHsl(hexRgb(original))[2];
        originalFacetLightness.set(poly, oldL);
      }
      /* Preserve each original facet's relative luminance and thus the
         geometric low-poly texture, rather than flattening to 5 colors. */
      const newL = Math.max(
        0.16,
        Math.min(0.83, baseLightness + (oldL - 0.44) * 0.78),
      );
      poly.style.setProperty(
        "fill",
        "hsl(" +
          facetHue +
          " " +
          (facetSaturation * 100).toFixed(1) +
          "% " +
          (newL * 100).toFixed(1) +
          "%)",
        "important",
      );
    });
  }
  const observer = new MutationObserver((records) => {
    if (records.some((record) => record.type === "childList")) repaint();
  });
  observer.observe(map, { childList: true });
  document.addEventListener("fbkk:themechange", repaint);
  repaint();
})();
